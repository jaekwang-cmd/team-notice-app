const assert = require('node:assert/strict');
const { chromium, expect } = require('@playwright/test');
const { createPreviewServer } = require('../scripts/premium-preview.cjs');

(async () => {
  const server = createPreviewServer();
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const origin = 'http://127.0.0.1:' + server.address().port;
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:860,height:640}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => route.request().url().startsWith(origin + '/') ? route.continue() : route.abort());
    await page.goto(origin + '/?auth=signed-out&view=journal');
    await page.waitForFunction(() => window.yeobaekReady);
    const frame = page.frameLocator('#simple-pane');
    const controls = page.locator('#mode-switch');
    const connect = page.locator('#simple-google-button');
    const monthTab = page.locator('[data-simple-page=month]');
    const dayTab = page.locator('[data-simple-page=day]');
    const today = frame.locator('.sdm-day[aria-current=date]');
    const form = page.locator('#event-form');
    const title = page.locator('#event-title');
    await expect(page.locator('#simple-pane')).toBeHidden();
    await controls.getByText('간편모드').click();
    await expect(connect).toHaveText('Google 연결');
    await expect(frame.locator('.boards')).toBeVisible();
    await expect(frame.locator('.secondary')).toBeVisible();
    const box = await frame.locator('.boards').boundingBox(), area = await page.locator('#simple-pane').boundingBox();
    assert(box.width >= area.width - 28 && Math.abs(area.y + area.height - box.y - box.height) < 16);
    const label = await monthTab.locator('.sidebar-nav-label').evaluate(el => {
      const css = getComputedStyle(el), row = el.parentElement;
      return {height:el.clientHeight,width:el.clientWidth,content:el.scrollWidth,font:css.fontSize,line:css.lineHeight,
        row:row.clientWidth,rail:row.parentElement.clientWidth,whiteSpace:css.whiteSpace,display:css.display,padding:getComputedStyle(row).padding};
    });
    assert(label.height < 24 && label.content <= label.width + 1, JSON.stringify(label));
    await frame.getByRole('button',{name:'오늘 할 일 추가'}).click();
    await frame.locator('.entry-form input').fill('기기 할 일');
    await frame.locator('.entry-form input').press('Enter');
    await expect(frame.getByText('기기 할 일',{exact:true})).toBeVisible();
    await frame.getByRole('button',{name:'오늘 할 일 추가'}).click();
    await frame.locator('.entry-form input').fill('이전 기기의 초안');
    await connect.click();
    await expect(connect).toHaveText('Google 연결됨');
    await expect(frame.getByText('기기 할 일',{exact:true})).toHaveCount(0);
    await expect(frame.locator('.entry-form input')).toHaveCount(0);
    await frame.getByRole('button',{name:'오늘 할 일 추가'}).click();
    await frame.locator('.entry-form input').fill('계정 할 일');
    await frame.locator('.entry-form input').press('Enter');
    await frame.getByRole('checkbox',{name:'계정 할 일'}).check();
    await expect(frame.getByRole('checkbox',{name:'계정 할 일'})).toBeChecked();
    console.log('PASS compact rail, full-width boards, device/account task and draft isolation');
    await monthTab.click();
    await today.click();
    await title.fill('간편모드 일정 회귀 확인');
    await form.getByRole('button',{name:'저장'}).click();
    await expect(form).toBeHidden();
    const event = page.locator('.day-event-item').filter({hasText:'간편모드 일정 회귀 확인'});
    await event.getByRole('button',{name:'수정'}).click();
    await title.fill('수정된 간편모드 일정');
    await form.getByRole('button',{name:'저장'}).click();
    const changed = page.locator('.day-event-item').filter({hasText:'수정된 간편모드 일정'});
    await changed.getByRole('button',{name:'삭제'}).click();
    await page.locator('.calendar-confirm').getByRole('button',{name:'삭제'}).click();
    await expect(changed).toHaveCount(0);
    const close = page.locator('#day-panel-close');
    const hit = await close.boundingBox();
    assert(hit.width >= 48 && hit.height >= 48);
    await page.mouse.click(hit.x+1,hit.y+1);
    await expect(page.locator('#simple-calendar-detail')).toBeHidden();
    await page.reload();
    await expect(page.locator('#simple-pane')).toBeVisible();
    await expect(frame.locator('.boards')).toBeVisible();
    await connect.click();
    await expect(connect).toHaveText('Google 연결됨');
    await connect.click();
    await page.locator('#simple-account-menu').getByRole('button',{name:'로그아웃'}).click();
    await expect(connect).toHaveText('Google 연결');
    await dayTab.click();
    await controls.getByText('기본모드').click();
    await expect(page.locator('#simple-pane')).toBeHidden();
    await expect(page.locator('#google-signin-button')).toBeVisible();
    assert.deepEqual(errors, []);
    console.log('PASS shared Google login, original calendar CRUD, 48px close, mode persistence and return to classic');
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode=1; });
